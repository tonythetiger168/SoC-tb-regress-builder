"""Generate tb/phone/phone_ss_ral.svh: UVM RAL blocks of the phone SoC
subsystem IPs, from the register map and field tables of open-ip-portfolio's
docs/ip/<P>.md (the pages are generated from the same JSON specs as the RTL).

usage: scripts/gen_phone_ss_ral.py <open-ip-portfolio checkout> > tb/phone/phone_ss_ral.svh
"""
import os, re, sys

# IP, block class prefix (order = APB slot in the subsystem segment, see phone_soc_pkg SS_*)
IPS = ["CPU_Cluster", "GPU", "NPU", "ISP", "Display_Controller", "Video_Codec", "Video_Codec",
       "Modem", "DMA", "Audio_DSP", "Sensor_Hub", "Interrupt_Controller", "Timer_WDT"]

ACC = {"RO": "RO", "RW": "RW", "W1C": "W1C", "WO (pulse)": "WO"}


def table(lines, start, stop):
    rows, on = [], False
    for ln in lines:
        if ln.startswith(start):
            on = True
            continue
        if on and ln.startswith(stop):
            break
        if on and ln.startswith("| ") and not ln.startswith("| Register") and not ln.startswith("| Offset") \
                and not ln.startswith("|---"):
            rows.append([c.strip() for c in ln.strip().strip("|").split("|")])
    return rows


def ident(s, used):
    s = s.strip("`")
    s = re.sub(r"[^A-Za-z0-9_]", "_", s).strip("_").upper() or "VAL"
    if not re.match(r"[A-Z_]", s):
        s = "F_" + s
    if s in ("ONE_BIT_PER_INTERRUPT",):
        s = "IRQ"
    base, n = s, 1
    while s in used:
        n += 1
        s = f"{base}{n}"
    used.add(s)
    return s


def parse(path):
    lines = open(path).read().splitlines()
    regs = []
    for off, name, acc, reset, *_ in table(lines, "### Register map", "### Fields"):
        regs.append({"off": int(off, 16), "name": name, "acc": ACC[acc], "reset": reset, "fields": []})
    by = {r["name"]: r for r in regs}
    for reg, bits, field, acc, reset, *_ in table(lines, "### Fields", "### Interrupts"):
        if reg not in by:
            continue
        hi, lo = (bits.split(":") + [bits])[:2] if ":" in bits else (bits, bits)
        by[reg]["fields"].append({"name": field, "lsb": int(lo), "width": int(hi) - int(lo) + 1,
                                  "acc": ACC[acc], "reset": reset})
    return regs


def emit(ip, regs):
    cls = ip.lower() + "_ss_block"
    out = [f"  class {cls} extends phone_ip_block;",
           f"    `uvm_object_utils({cls})",
           f"    function new(string name = \"{cls}\"); super.new(name); endfunction",
           "    function void build();",
           "      phone_reg r;",
           "      default_map = create_map(\"map\", 0, 4, UVM_LITTLE_ENDIAN);"]
    for r in regs:
        out.append(f"      r = add_reg(\"{r['name']}\", 'h{r['off']:03X}, \"{r['acc']}\");")
        fields = r["fields"] or [{"name": "VAL", "lsb": 0, "width": 32, "acc": r["acc"], "reset": r["reset"]}]
        used = set()
        for f in sorted(fields, key=lambda f: f["lsb"]):
            core = f["reset"] == "core"
            rst = 0 if core else int(f["reset"], 16)
            # hardware-updated: core outputs, W1C status, non-ID read-only words
            vol = int(core or f["acc"] == "W1C" or (f["acc"] == "RO" and r["name"] != "ID"))
            out.append(f"      r.add_field(\"{ident(f['name'], used)}\", {f['lsb']}, {f['width']}, "
                       f"\"{f['acc']}\", 'h{rst:X}, {vol}, {int(not core)});")
    out.append("      finish();")
    out += ["    endfunction", "  endclass", ""]
    return "\n".join(out)


def main():
    src = sys.argv[1]
    print("// SPDX-License-Identifier: Apache-2.0")
    print("// Generated by scripts/gen_phone_ss_ral.py from open-ip-portfolio docs/ip/<P>.md. Do not edit.")
    print("// RAL blocks of the phone SoC subsystem IPs (included by phone_ral_pkg).")
    done = set()
    for ip in IPS:
        if ip in done:
            continue
        done.add(ip)
        print(emit(ip, parse(os.path.join(src, "docs", "ip", ip + ".md"))))


if __name__ == "__main__":
    main()
