"""socgen manycore: an OpenPiton-style tiled many-core SoC and its UVM bench.

A spec with a `manycore:` section (instead of masters/slaves/noc) describes an
X x Y mesh of tiles. The RTL comes from minisim's bench/gen_manycore.py (one
generator for both projects): each tile has a RISC-V core, private RAM, a
write-through L1, a slice of the shared L2 with a limited-pointer coherence
directory, and three NoC routers (requests, responses/invalidations, acks).
Every core runs the same shared-memory program: rounds of computation, a
barrier, and an exchange with tiles i+1 and i+X.

This module writes, under socgen/out/<soc>/:
  rtl/<soc>.sv          the design (generated, our own RTL)
  tb/<soc>_pkg.sv       UVM env: NoC monitor (functional coverage per network
                        and message type, hop counts, invalidation fan-out,
                        per-request latency tile -> home L2), scoreboard with
                        a reference model of the program
  tb/<soc>_tb_top.sv    clock/reset, backdoor configuration of the program,
                        NoC probes, L2 snapshot for the scoreboard
  sim/files.f, socgen.mk
and regress/suites/<soc>.yaml with regress/<soc>_testlist.txt.

The scoreboard checks every core's final value in the shared memory (read
from the L2 slices) and the checksum core 0 computed, so a pass means the
coherence protocol, the NoC and the cores all behaved.

spec:
  socgen: 1
  soc: {name: manycore_4x4, desc: ...}
  manycore:
    mesh: 4x4                # X x Y tiles
    core: mcrv               # mcrv | picorv32 | femtorv32 | cva6 | mix | comma list
    l2_lines: 64             # lines per L2 slice
    dir_ptrs: 4              # directory pointers before broadcast
    core_files: [...]        # extra sources for picorv32/femtorv32/cva6 (-f allowed)
    regress: true            # suite on by default (default: up to 16 tiles; bigger
                             # meshes run with --suite <name>)
"""
import importlib.util
import os

from spec import SpecError


def _load_gen(minisim_root):
    path = os.path.join(minisim_root, "bench", "gen_manycore.py")
    if not os.path.exists(path):
        raise SpecError(f"manycore: {path} not found (pass --minisim-root or set MINISIM_ROOT)")
    sp = importlib.util.spec_from_file_location("gen_manycore", path)
    mod = importlib.util.module_from_spec(sp)
    sp.loader.exec_module(mod)
    return mod


def _pkg(soc, i):
    n, x = i["n"], i["x"]
    fw = 2 * (i["xw"] + i["yw"]) + 163
    max_hops = (i["x"] - 1) + (i["y"] - 1)
    return f"""// SPDX-License-Identifier: Apache-2.0
// Generated by socgen (socgen/lib/manycore.py): UVM environment for {soc},
// a {i['x']}x{i['y']} tiled many-core ({n} tiles, cores: {'+'.join(i['cores'])}).
`include "uvm_macros.svh"
interface {soc}_ctl_if (input logic clk);
  logic rst_n = 1'b0;
  logic cfg_load = 1'b0, snap = 1'b0;
  int cfg_rounds, cfg_work;
  logic [{n - 1}:0] done;
  logic [31:0] result;
  longint unsigned cycles;
  logic [31:0] l2img [{n}][{i['l2_lines']}][4];   // L2 slices at the end of the run
endinterface

package {soc}_pkg;
  import uvm_pkg::*;
  import fcov_pkg::*;
  import lat_pkg::*;

  localparam int N = {n}, X = {x}, Y = {i['y']}, XW = {i['xw']}, YW = {i['yw']}, FW = {fw};
  localparam int L2_LINES = {i['l2_lines']};
  localparam int R0 = 'h{i['r0']:x}, R1 = 'h{i['r1']:x}, S = 'h{i['s']:x};
  localparam bit [31:0] GOLD = 32'h{i['gold']:08x};

  // ---------------------------------------------------------------- monitor
  // Fed by the probes in the tb top: one call per flit entering (inject) or
  // leaving (eject) the mesh at a tile, per network.
  class {soc}_noc_mon;
    static fcov_group g;
    static longint unsigned cyc;
    static longint unsigned t_req [N];          // cycle of the tile's outstanding request
    static int unsigned req_t [N];              // its type
    static int unsigned n_inv [N];              // invalidations a home has sent for its current write
    static longint unsigned n_flits [3];

    static function void init();
      if (g != null) return;
      g = fcov_db::group("{soc}_noc", "noc");
      g.add_bins("noc1", '{{"rd", "wr", "amo"}});
      g.add_bins("noc2", '{{"data", "wack", "inv"}});
      g.add_bins("noc3", '{{"iack"}});
      for (int h = 0; h <= {max_hops}; h++) g.bin("req_hops", $sformatf("h%0d", h));
      g.add_bins("inv_fanout", '{{"none", "one", "two_to_ptrs", "broadcast"}});
      for (int k = 0; k < N; k++) g.bin("home", $sformatf("l2_%0d", k));
    endfunction

    static function void flit(int tile, int net, bit inject, logic [FW-1:0] f);
      int dx, dy, sid, ty, home, sx, sy;
      init();
      dx = int'(f[FW-1 -: XW]);
      dy = int'(f[FW-1-XW -: YW]);
      sx = int'(f[FW-1-XW-YW -: XW]);
      sy = int'(f[FW-1-XW-YW-XW -: YW]);
      sid = sy * X + sx;
      ty = int'(f[FW-1-2*(XW+YW) -: 3]);
      if (ty < 1 || ty > 7) return;
      if (inject) begin
        n_flits[net]++;
        g.hit(net == 0 ? "noc1" : net == 1 ? "noc2" : "noc3", name_of(ty - 1));
        if (net == 0) begin                      // a core's request leaves its tile
          t_req[tile] = cyc;
          req_t[tile] = ty;
          g.hit("req_hops", $sformatf("h%0d", (dx > sx ? dx - sx : sx - dx) + (dy > sy ? dy - sy : sy - dy)));
          g.hit("home", $sformatf("l2_%0d", dy * X + dx));
        end
        if (net == 1 && ty == 6) n_inv[tile]++;
        if (net == 1 && ty == 5) begin           // the home acknowledges a write: fan-out is known
          g.hit("inv_fanout", n_inv[tile] == 0 ? "none" : n_inv[tile] == 1 ? "one" :
                              n_inv[tile] < N - 1 ? "two_to_ptrs" : "broadcast");
          n_inv[tile] = 0;
        end
      end else if (net == 1 && (ty == 4 || ty == 5)) begin
        // the response reaches the requesting tile: latency from request injection
        home = sid;
        lat_db::add($sformatf("T%0d", tile), $sformatf("L2_%0d", home), req_t[tile] == 2 ? "W" : "R",
                    cyc - t_req[tile]);
      end
    endfunction

    static function string name_of(int k);
      case (k)
        0: return "rd"; 1: return "wr"; 2: return "amo"; 3: return "data";
        4: return "wack"; 5: return "inv"; default: return "iack";
      endcase
    endfunction
  endclass

  // ---------------------------------------------------------------- model
  // The program every core runs (same as bench/gen_manycore.py's golden()).
  class {soc}_model;
    static function bit [31:0] xs(bit [31:0] t);
      t ^= t << 13; t ^= t >> 17; t ^= t << 5;
      return t;
    endfunction
    static function void run(int rounds, int work, output bit [31:0] v [N], output bit [31:0] chk);
      bit [31:0] r [N];
      for (int k = 0; k < N; k++) v[k] = (k + 1) ^ GOLD;
      for (int rd = 0; rd < rounds; rd++) begin
        for (int k = 0; k < N; k++)
          for (int s = 0; s < work + ((k & 15) << 3); s++) v[k] = xs(v[k]);
        r = v;
        for (int k = 0; k < N; k++) v[k] = v[k] + (r[(k + 1) % N] ^ r[(k + X) % N]);
      end
      chk = 0;
      for (int k = 0; k < N; k++) chk = {{chk[30:0], chk[31]}} ^ v[k];
    endfunction
  endclass

  // ---------------------------------------------------------------- env
  class {soc}_env extends uvm_env;
    `uvm_component_utils({soc}_env)
    virtual {soc}_ctl_if vif;
    int rounds, work;
    function new(string name, uvm_component parent); super.new(name, parent); endfunction
    function void build_phase(uvm_phase phase);
      if (!uvm_config_db#(virtual {soc}_ctl_if)::get(this, "", "vif", vif))
        `uvm_fatal("NOVIF", "no {soc}_ctl_if")
    endfunction

    // runs the program with the given parameters and checks the result
    task run_program(int rounds_, int work_);
      longint unsigned limit, c;
      rounds = rounds_;
      work = work_;
      limit = longint'(rounds) * ((work + 120) * 64 + 64 * N + 2000) + 64 * N + 10000;
      `uvm_info("MC", $sformatf("{x}x{i['y']} mesh: rounds=%0d work=%0d (limit %0d cycles)", rounds, work, limit), UVM_LOW)
      vif.rst_n <= 1'b0;
      vif.cfg_rounds <= rounds;
      vif.cfg_work <= work;
      repeat (2) @(posedge vif.clk);
      vif.cfg_load <= 1'b1;                     // the tb top writes both words into every tile's RAM
      @(posedge vif.clk);
      vif.cfg_load <= 1'b0;
      repeat (2) @(posedge vif.clk);
      vif.rst_n <= 1'b1;
      c = 0;
      while (!(&vif.done) && c < limit) begin
        @(posedge vif.clk);
        c++;
      end
      vif.cycles = c;
      vif.snap <= 1'b1;                         // copy the L2 slices for the scoreboard
      @(posedge vif.clk);
      vif.snap <= 1'b0;
      @(posedge vif.clk);
      check();
    endtask

    int n_checks, n_errors;
    function void check();
      bit [31:0] v [N], chk;
      {soc}_model::run(rounds, work, v, chk);
      for (int k = 0; k < N; k++) begin
        n_checks++;
        if (!vif.done[k]) begin
          n_errors++;
          `uvm_error("SB", $sformatf("tile %0d did not finish in %0d cycles", k, vif.cycles))
        end
      end
      for (int k = 0; k < N; k++) begin
        int off, line;
        bit [31:0] got;
        off = S + 4 * k;
        line = off >> 4;
        got = vif.l2img[line % N][line / N][(off >> 2) % 4];
        n_checks++;
        if (got !== v[k]) begin
          n_errors++;
          `uvm_error("SB", $sformatf("core %0d final value in L2 = %h, model %h", k, got, v[k]))
        end
      end
      n_checks++;
      if (vif.result !== chk) begin
        n_errors++;
        `uvm_error("SB", $sformatf("checksum %h, model %h", vif.result, chk))
      end
      `uvm_info("MC", $sformatf("finished in %0d cycles, checksum %h (model %h), flits noc1=%0d noc2=%0d noc3=%0d",
                vif.cycles, vif.result, chk, {soc}_noc_mon::n_flits[0], {soc}_noc_mon::n_flits[1],
                {soc}_noc_mon::n_flits[2]), UVM_LOW)
    endfunction

    function void report_phase(uvm_phase phase);
      if ({soc}_noc_mon::g != null) {soc}_noc_mon::g.dump();
      if (n_errors == 0 && n_checks > 0) $display("SB_PASS checks=%0d", n_checks);
      else $display("SB_FAIL errors=%0d checks=%0d", n_errors, n_checks);
    endfunction
  endclass

  // ---------------------------------------------------------------- tests
  class {soc}_base_test extends uvm_test;
    `uvm_component_utils({soc}_base_test)
    {soc}_env env;
    int rounds = 2, work = 8;
    function new(string name, uvm_component parent); super.new(name, parent); endfunction
    function void build_phase(uvm_phase phase);
      env = {soc}_env::type_id::create("env", this);
    endfunction
    virtual function void pick();
    endfunction
    task run_phase(uvm_phase phase);
      phase.raise_objection(this);
      pick();
      void'($value$plusargs("MC_ROUNDS=%d", rounds));
      void'($value$plusargs("MC_WORK=%d", work));
      env.run_program(rounds, work);
      phase.drop_objection(this);
    endtask
  endclass

  // two short rounds
  class {soc}_smoke_test extends {soc}_base_test;
    `uvm_component_utils({soc}_smoke_test)
    function new(string name, uvm_component parent); super.new(name, parent); endfunction
  endclass

  // rounds and work per seed
  class {soc}_random_test extends {soc}_base_test;
    `uvm_component_utils({soc}_random_test)
    function new(string name, uvm_component parent); super.new(name, parent); endfunction
    function void pick();
      rounds = $urandom_range(6, 1);
      work = $urandom_range(64, 1);
    endfunction
  endclass

  // almost no computation: barriers and invalidations back to back
  class {soc}_barrier_test extends {soc}_base_test;
    `uvm_component_utils({soc}_barrier_test)
    function new(string name, uvm_component parent); super.new(name, parent); endfunction
    function void pick();
      rounds = 8;
      work = 1;
    endfunction
  endclass

  // long rounds: most cores wait at the barrier while the slowest compute
  class {soc}_long_test extends {soc}_base_test;
    `uvm_component_utils({soc}_long_test)
    function new(string name, uvm_component parent); super.new(name, parent); endfunction
    function void pick();
      rounds = 4;
      work = 96;
    endfunction
  endclass
endpackage
"""


def _top(soc, i):
    n = i["n"]
    fw = 2 * (i["xw"] + i["yw"]) + 163
    return f"""// SPDX-License-Identifier: Apache-2.0
// Generated by socgen (socgen/lib/manycore.py): testbench top for {soc}.
// The control interface is in {soc}_pkg.sv.
`timescale 1ns/1ps

module {soc}_tb_top;
  import uvm_pkg::*;
  logic clk = 1'b0;
  always #1 clk = ~clk;
  {soc}_ctl_if ctl(clk);
  logic [31:0] l2req [{n}];
  mc_soc dut(.clk(clk), .rst_n(ctl.rst_n), .done(ctl.done), .result(ctl.result), .l2req(l2req));

  always @(posedge clk) {soc}_pkg::{soc}_noc_mon::cyc++;
  for (genvar ty = 0; ty < {i['y']}; ty++) begin : py
    for (genvar tx = 0; tx < {i['x']}; tx++) begin : px
      localparam int T = ty * {i['x']} + tx;
      // program parameters, written into the private RAM while reset is held
      always @(posedge clk)
        if (ctl.cfg_load) begin
          dut.row[ty].col[tx].t.ram[{i['d_rounds'] // 4}] = 32'(ctl.cfg_rounds);
          dut.row[ty].col[tx].t.ram[{i['d_work'] // 4}] = 32'(ctl.cfg_work);
        end
      // NoC probes at the tile's local router ports (0 NoC1, 1 NoC2, 2 NoC3)
      for (genvar n = 0; n < 3; n++) begin : pn
        always @(posedge clk) begin
          if (dut.row[ty].col[tx].t.tv[n] && dut.row[ty].col[tx].t.tr[n])
            {soc}_pkg::{soc}_noc_mon::flit(T, n, 1'b1, {fw}'(dut.row[ty].col[tx].t.tf[n]));
          if (dut.row[ty].col[tx].t.lv[n] && dut.row[ty].col[tx].t.lr[n])
            {soc}_pkg::{soc}_noc_mon::flit(T, n, 1'b0, {fw}'(dut.row[ty].col[tx].t.lf[n]));
        end
      end
      always @(posedge clk)
        if (ctl.snap)
          for (int l = 0; l < {i['l2_lines']}; l++)
            for (int w = 0; w < 4; w++) ctl.l2img[T][l][w] = dut.row[ty].col[tx].t.l2.mem[l][w*32 +: 32];
    end
  end

  initial begin
    uvm_config_db#(virtual {soc}_ctl_if)::set(null, "uvm_test_top.*", "vif", ctl);
    run_test();
  end
endmodule
"""


def generate(raw, out, minisim_root, spec_path, repo_files, root):
    soc = raw["soc"]["name"]
    mc = raw["manycore"]
    gen = _load_gen(minisim_root)
    argv = ["--mesh", str(mc.get("mesh", "4x4")), "--core", str(mc.get("core", "mcrv")),
            "--l2-lines", str(mc.get("l2_lines", 64)), "--dir-ptrs", str(mc.get("dir_ptrs", 4))]
    args = gen.parser().parse_args(argv)
    try:
        text, info = gen.generate(args, " ".join(argv))
    except gen.GenError as e:
        raise SpecError(f"manycore: {e}")
    rel = os.path.relpath(out, root)
    files = {
        f"rtl/{soc}.sv": text,
        f"tb/{soc}_pkg.sv": _pkg(soc, info),
        f"tb/{soc}_tb_top.sv": _top(soc, info),
    }
    flist = list(mc.get("core_files", []))
    flist += ["vip/common/fcov_pkg.sv", "vip/common/lat_pkg.sv", f"{rel}/rtl/{soc}.sv",
              f"{rel}/tb/{soc}_pkg.sv", f"{rel}/tb/{soc}_tb_top.sv"]
    files["sim/files.f"] = "\n".join(flist) + "\n"
    files["socgen.mk"] = (f"# generated by socgen from {os.path.relpath(spec_path, root)}\n"
                          f"TOP_{soc} := {soc}_tb_top\nFLIST_{soc} := {rel}/sim/files.f\n")
    written = []
    for p, t in files.items():
        full = os.path.join(out, p)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w") as f:
            f.write(t)
        written.append(full)
    if repo_files:
        tests = [(f"{soc}_smoke_test", 2), (f"{soc}_random_test", 4), (f"{soc}_barrier_test", 1),
                 (f"{soc}_long_test", 1)]
        lst = os.path.join(root, "regress", f"{soc}_testlist.txt")
        with open(lst, "w") as f:
            f.write(f"# generated by socgen from {os.path.relpath(spec_path, root)}\n")
            for t, seeds in tests:
                f.write(f"{t} {seeds}\n")
        suite = os.path.join(root, "regress", "suites", f"{soc}.yaml")
        with open(suite, "w") as f:
            f.write(f"""# generated by socgen from {os.path.relpath(spec_path, root)}
name: {soc}
level: soc
soc: manycore
description: {raw['soc'].get('desc', soc)}
filelist: {rel}/sim/files.f
top: {soc}_tb_top
list:
  default: regress/{soc}_testlist.txt
cov_include: ['{rel}/rtl/*']
timeout: {int(mc.get('timeout', 1800))}
enabled: {'true' if mc.get('regress', info['n'] <= 16) else 'false'}
""")
        written += [lst, suite]
    return written, info
