"""Read what socgen needs from an open-ip-portfolio checkout:
  * docs/ip/<IP>.md  "Register map" and "Fields" tables  -> RAL registers
  * rtl/<IP>_apb.sv  module header                        -> params and pass-through pins
Both files are generated by open-ip's scripts/apb/gen_apb.py from the same
JSON spec as the RTL, so the RAL offsets always match the wrapper."""
import os
import re

from spec import Obj, SpecError

APB_PINS = {"PCLK", "PRESETN", "PSEL", "PENABLE", "PWRITE", "PADDR", "PWDATA", "PSTRB",
            "PRDATA", "PREADY", "PSLVERR"}


def _table(md, heading):
    m = re.search(rf"^###\s+{re.escape(heading)}\s*$(.*?)(?=^#)", md + "\n#", re.M | re.S)
    if not m:
        return []
    rows = []
    for line in m.group(1).splitlines():
        line = line.strip()
        if not line.startswith("|") or set(line) <= set("|-: "):
            continue
        cells = [c.strip() for c in re.split(r"(?<!\\)\|", line.strip("|"))]
        rows.append(cells)
    return rows[1:]                      # drop the header row


def _acc(a):
    """open-ip access string -> (RAL access, volatile, testable)"""
    a = a.strip()
    base = a.split()[0]
    core = "(core)" in a
    pop = "(pop)" in a
    pulse = "(pulse)" in a
    ral = {"RO": "RO", "RW": "RW", "W1C": "W1C", "WO": "WO"}.get(base)
    if ral is None:
        raise SpecError(f"unknown open-ip access {a!r}")
    return ral, core or pop or base == "W1C", not (core or pop or pulse)


def _int(s):
    s = s.strip().strip("`")
    return None if s == "core" else int(s, 0)


def registers(ip_root, ip):
    path = os.path.join(ip_root, "docs", "ip", f"{ip}.md")
    if not os.path.exists(path):
        raise SpecError(f"open-ip IP {ip!r}: {path} not found (check --ip-root)")
    with open(path) as f:
        md = f.read()
    rmap = _table(md, "Register map")
    if not rmap:
        raise SpecError(f"{path}: no Register map table")
    fields = {}
    for r in _table(md, "Fields"):
        reg, bits, name, acc, reset = r[0], r[1], r[2], r[3], r[4]
        msb, _, lsb = bits.partition(":")
        msb = int(msb)
        lsb = int(lsb) if lsb else msb
        fname = re.sub(r"\W", "_", name.strip("`")).upper()
        if not re.match(r"^[A-Z_][A-Z0-9_]*$", fname) or " " in name and "`" not in name:
            fname = f"F{lsb}"
        fields.setdefault(reg, []).append((lsb, msb - lsb + 1, fname, acc, reset))
    regs = []
    for r in rmap:
        off, name, acc, reset = int(r[0], 16), r[1], r[2], r[3]
        ral, vol, testable = _acc(acc)
        rst = _int(reset)
        fl = []
        used = set()
        for lsb, w, fname, facc, freset in sorted(fields.get(name, [])):
            fa, fv, ft = _acc(facc)
            fr = _int(freset)
            if fname in used:
                fname = f"{fname}_{lsb}"
            used.add(fname)
            fl.append(Obj(name=fname, lsb=lsb, width=w, access=fa, volatile=fv or fr is None,
                          reset=fr or 0))
        if not fl:
            fl = [Obj(name="VAL", lsb=0, width=32, access=ral, volatile=vol or rst is None,
                      reset=rst or 0)]
        regs.append(Obj(name=name, offset=off, access=ral, volatile=vol or rst is None,
                        testable=testable and rst is not None, core=rst is None,
                        reset=sum(f.reset << f.lsb for f in fl), fields=fl, desc=r[4] if len(r) > 4 else ""))
    # Only spec kind "rw" registers read back what was written; stream holding
    # registers (stream_in), bus ports and command pulses do not.
    jpath = os.path.join(ip_root, "scripts", "apb", "specs", f"{ip}.json")
    if os.path.exists(jpath):
        import json
        with open(jpath) as f:
            kinds = {r["name"]: r["kind"] for r in json.load(f).get("regs", [])}
        for r in regs:
            k = kinds.get(r.name) or kinds.get(re.sub(r"\d+$", "", r.name))
            if k is not None and k != "rw":
                r.testable = False
                r.volatile = True
    # FLAGS is a word gen_apb adds to every IP (not in the JSON regs): it
    # shows live stream state (TX full, RX available), so its value after
    # reset depends on the core and the test must not check it.
    for r in regs:
        if r.name == "FLAGS":
            r.testable = False
            r.volatile = True
            for f in r.fields:
                f.volatile = True
    idreg = next((r for r in regs if r.name == "ID"), None)
    return Obj(regs=regs, id=idreg.reset if idreg else None, doc=os.path.relpath(path, ip_root))


def _eval_width(expr, params):
    if expr is None:
        return 1
    m = re.fullmatch(r"\[(.+):(.+)\]", expr.replace(" ", ""))
    if not m:
        raise SpecError(f"can't parse width {expr!r}")
    env = dict(params)
    hi = eval(m.group(1), {"__builtins__": {}}, env)      # noqa: S307 - integer params only
    lo = eval(m.group(2), {"__builtins__": {}}, env)
    return int(hi) - int(lo) + 1


def wrapper(ip_root, ip, overrides):
    path = os.path.join(ip_root, "rtl", f"{ip}_apb.sv")
    if not os.path.exists(path):
        raise SpecError(f"open-ip IP {ip!r}: {path} not found")
    src = open(path).read()
    m = re.search(rf"^module\s+{ip}_apb\s*(#\s*\((.*?)\))?\s*\((.*?)\);", src, re.M | re.S)
    if not m:
        raise SpecError(f"{path}: module header not found")
    params = {}
    for pm in re.finditer(r"parameter\s+(?:int\s+(?:unsigned\s+)?|integer\s+)?(\w+)\s*=\s*([^,\n)]+)",
                          m.group(2) or ""):
        v = pm.group(2).strip().replace("_", "")
        try:
            params[pm.group(1)] = int(v, 0)
        except ValueError:
            params[pm.group(1)] = v
    for k in overrides:
        if k not in params:
            raise SpecError(f"{ip}_apb has no parameter {k!r} (has {sorted(params)})")
    eff = {**params, **overrides}
    pins = []
    for line in m.group(3).splitlines():
        line = re.sub(r"//.*", "", line).strip().rstrip(",")
        pm = re.match(r"(input|output|inout)\s+(?:logic|wire|tri)?\s*(?:logic)?\s*(\[[^\]]+\])?\s*(\w+)$", line)
        if not pm or pm.group(3) in APB_PINS or pm.group(3) == "irq":
            continue
        pins.append(Obj(dir=pm.group(1), name=pm.group(3),
                        width=_eval_width(pm.group(2), {k: v for k, v in eff.items()
                                                        if isinstance(v, int)})))
    has_irq = re.search(r"output\s+logic\s+irq\b", m.group(3)) is not None
    return Obj(params=params, pins=pins, has_irq=has_irq, files=[f"rtl/{ip}_top.sv", f"rtl/{ip}_apb.sv"])


def commit(ip_root):
    head = os.path.join(ip_root, ".git", "HEAD")
    try:
        import subprocess
        return subprocess.run(["git", "-C", ip_root, "rev-parse", "HEAD"], capture_output=True,
                              text=True, check=True).stdout.strip()
    except Exception:
        return open(head).read().strip() if os.path.exists(head) else "unknown"
